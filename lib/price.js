// Ціна картини зберігається як чисте число-рядок (без "€") — так адмінка
// не змушує вводити валюту вручну, а знак додається лише при показі.
// normalizePrice заодно захищає від подвійного "€", якщо хтось таки
// вставить його в поле: усе, крім цифр і десяткового роздільника, зрізається.
export function normalizePrice(raw) {
  return String(raw ?? "").replace(/[^\d.,]/g, "").trim();
}

// Нерозривні пробіли: ціна не має розриватися на кінці рядка ні між
// тисячами, ні перед знаком валюти.
const NBSP = "\u00A0";

// normalizePrice тут теж — щоб старі значення "€ 325" зі сховища
// (продакшн-дані, які ця зміна не мігрує) не показались як "€ € 325".
//
// Формат за локаллю: uk/ru/pl/de — "3 900 €" (знак після числа),
// en — "€3,900" (знак попереду, кома в тисячах). Локаль передає той,
// хто показує ціну; лист художникові лишається українським за замовчуванням.
export function formatPrice(price, locale = "uk") {
  const clean = normalizePrice(price);
  if (!clean) return "";

  // Ціна — ціле число євро; копійки трапляються лише хвостом ",50"/".50".
  // Усе інше (напр. "3,900", де кома була роздільником тисяч) зводимо
  // до самих цифр, інакше сотні перетворилися б на копійки.
  const parts = clean.match(/^(\d+)(?:[.,](\d{1,2}))?$/);
  const whole = parts ? parts[1] : clean.replace(/\D/g, "");
  const cents = parts ? parts[2] : "";
  if (!whole) return "";

  const group = (sep) => whole.replace(/\B(?=(\d{3})+(?!\d))/g, sep);

  if (locale === "en") {
    return `€${group(",")}${cents ? `.${cents}` : ""}`;
  }
  return `${group(NBSP)}${cents ? `,${cents}` : ""}${NBSP}€`;
}
